"""Fixture footprints: the stock and its registration pins, drawn in KiCad.

A fixture footprint has no pads or holes, only graphics on a user layer, so it
never reaches the Gerbers or the drill file. Its origin is the stock's
lower-left corner, i.e. work zero: where the footprint sits on the board is
where the board will be cut.
"""

from __future__ import annotations

import math
import re
from dataclasses import dataclass
from pathlib import Path

from .config import Fixture, FixtureStock

LIBRARY = "pcbcam-fixtures"
PROP_FIXTURE = "pcbcam_fixture"
PROP_STOCK = "pcbcam_stock"
PROP_GEOMETRY = "pcbcam_geometry"


def _fmt(v: float) -> str:
    return f"{v:.4f}".rstrip("0").rstrip(".")


def footprint_name(fixture: Fixture, key: str) -> str:
    return f"Stock_{key}_Pins{_fmt(fixture.pin_diameter_mm)}mm"


def geometry(fixture: Fixture, key: str) -> str:
    """Everything a footprint was drawn from; a placed footprint must match it."""
    s = fixture.stocks[key]
    pins = " ".join(f"{_fmt(x)},{_fmt(y)}" for x, y in s.pins_mm)
    return (f"stock={_fmt(s.size_x_mm)}x{_fmt(s.size_y_mm)};flip={s.flip};pin={_fmt(fixture.pin_diameter_mm)};"
            f"pins={pins};clearance={_fmt(fixture.pin_clearance_mm)};edge={_fmt(fixture.edge_margin_mm)};"
            f"origin={fixture.work_origin}")


# --- footprint generation -----------------------------------------------------


def _text(kind: str, value: str, x: float, y: float, layer: str, size: float, hide: bool = False,
          justify: str = "") -> str:
    head = f'(property "{kind}" "{value}"' if kind else f'(fp_text user "{value}"'
    return (f'\t{head}\n\t\t(at {_fmt(x)} {_fmt(y)} 0)\n\t\t(layer "{layer}")\n'
            + ("\t\t(hide yes)\n" if hide else "")
            + f"\t\t(effects\n\t\t\t(font\n\t\t\t\t(size {_fmt(size)} {_fmt(size)})\n"
            f"\t\t\t\t(thickness {_fmt(size * 0.15)})\n\t\t\t)\n"
            + (f"\t\t\t(justify {justify})\n" if justify else "")
            + "\t\t)\n\t)\n")


def _stroke(width: float, kind: str) -> str:
    return f"\t\t(stroke\n\t\t\t(width {_fmt(width)})\n\t\t\t(type {kind})\n\t\t)\n"


def _line(x0, y0, x1, y1, layer, width=0.1, kind="solid") -> str:
    return (f"\t(fp_line\n\t\t(start {_fmt(x0)} {_fmt(y0)})\n\t\t(end {_fmt(x1)} {_fmt(y1)})\n"
            + _stroke(width, kind) + f'\t\t(layer "{layer}")\n\t)\n')


def _rect(x0, y0, x1, y1, layer, width=0.1, kind="solid") -> str:
    return (f"\t(fp_rect\n\t\t(start {_fmt(x0)} {_fmt(y0)})\n\t\t(end {_fmt(x1)} {_fmt(y1)})\n"
            + _stroke(width, kind) + f'\t\t(fill no)\n\t\t(layer "{layer}")\n\t)\n')


def _circle(cx, cy, r, layer, width=0.1, kind="solid") -> str:
    return (f"\t(fp_circle\n\t\t(center {_fmt(cx)} {_fmt(cy)})\n\t\t(end {_fmt(cx + r)} {_fmt(cy)})\n"
            + _stroke(width, kind) + f'\t\t(fill no)\n\t\t(layer "{layer}")\n\t)\n')


def render_footprint(fixture: Fixture, key: str) -> str:
    """A ``.kicad_mod`` for one stock size. KiCad's Y axis points down, so the
    stock frame's (x, y) is drawn at (x, -y)."""
    s: FixtureStock = fixture.stocks[key]
    w, h, lay = s.size_x_mm, s.size_y_mm, fixture.layer
    r = fixture.pin_diameter_mm / 2
    name = footprint_name(fixture, key)
    hidden = [(PROP_FIXTURE, fixture.name), (PROP_STOCK, key), (PROP_GEOMETRY, geometry(fixture, key))]

    zero = ("the lower-left pin" if fixture.work_origin == "lower_left_pin"
            else "the stock lower-left corner")
    out = [
        f'(footprint "{name}"\n\t(version 20260206)\n\t(generator "pcbcam")\n\t(layer "F.Cu")\n',
        f'\t(descr "pcbcam fixture {fixture.name}: {_fmt(w)} x {_fmt(h)} mm stock, '
        f'{_fmt(fixture.pin_diameter_mm)} mm registration pins. Work zero = {zero}. '
        f'Generated by pcbcam fixture-footprint, do not edit.")\n',
        f'\t(tags "pcbcam fixture stock")\n',
        # No number on purpose: KiBot 1.9 crashes on board-only footprints in its
        # filters (no parent sheet) and skips the ones with an unnumbered reference.
        _text("Reference", "FIXTURE", 0, 2, lay, 1, hide=True),
        _text("Value", name, 0, 4, lay, 1, hide=True),
        *(_text(k, v, 0, 0, lay, 1, hide=True) for k, v in hidden),
        "\t(attr board_only exclude_from_pos_files exclude_from_bom allow_missing_courtyard)\n",
        "\t(duplicate_pad_numbers_are_jumpers no)\n",
        # The stock, and where the board outline may go.
        _rect(0, -h, w, 0, lay, 0.3),
    ]
    e = fixture.edge_margin_mm
    if e > 0:
        out.append(_rect(e, -(h - e), w - e, -e, lay, 0.1, "dash"))
    # The flip axis: the stock centre line.
    axis, c = s.flip_axis()
    out.append(_line(c, 0, c, -h, lay, 0.1, "dash_dot") if axis == "x"
               else _line(0, -c, w, -c, lay, 0.1, "dash_dot"))
    # The pins: the pin itself, the zone the board outline must stay out of,
    # and a centre cross.
    for x, y in s.pins_mm:
        out.append(_circle(x, -y, r, lay, 0.2))
        if fixture.pin_clearance_mm > 0:
            out.append(_circle(x, -y, r + fixture.pin_clearance_mm, lay, 0.1, "dash"))
        out.append(_line(x - r, -y, x + r, -y, lay, 0.05))
        out.append(_line(x, -y - r, x, -y + r, lay, 0.05))
    # Work zero marker, at the real g-code origin (lower-left pin, or the corner).
    ox, oy = fixture.origin_shift(s)
    out.append(_line(ox, -oy, ox + 5, -oy, lay, 0.3))
    out.append(_line(ox, -oy, ox, -oy - 5, lay, 0.3))
    out.append(_text("", "X0 Y0 (work zero)", ox, -oy + 2.5, lay, 1.5, justify="left"))
    if (ox, oy) != (0, 0):
        # The stock corner is the zero for the separate 00_register blank-bore setup.
        out.append(_line(0, 0, 3, 0, lay, 0.15))
        out.append(_line(0, 0, 0, -3, lay, 0.15))
        out.append(_text("", "corner: 00_register zero", 6, -1, lay, 1, justify="left"))
    out.append(_text("", f"{fixture.name}: stock {_fmt(w)} x {_fmt(h)} mm, pins {_fmt(fixture.pin_diameter_mm)} mm"
                     + ("" if fixture.verified else " (UNVERIFIED pin positions)"),
                     0, 5, lay, 1.5, justify="left"))
    out.append("\t(embedded_fonts no)\n)\n")
    return "".join(out)


def write_library(fixture: Fixture, out: Path) -> list[Path]:
    """Write one footprint per stock size into a ``.pretty`` folder."""
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for key in fixture.stocks:
        path = out / f"{footprint_name(fixture, key)}.kicad_mod"
        path.write_text(render_footprint(fixture, key), encoding="utf-8", newline="\n")
        written.append(path)
    return written


# --- reading a placed footprint -------------------------------------------------

_TOKEN = re.compile(r'\s*(?:(\()|(\))|"((?:[^"\\]|\\.)*)"|([^\s()"]+))')


def parse_sexpr(text: str) -> list:
    """KiCad s-expression -> nested lists of strings (quoted or not)."""
    stack: list[list] = [[]]
    pos = 0
    while True:
        m = _TOKEN.match(text, pos)
        if not m:
            if text[pos:].strip():
                raise ValueError(f"cannot parse s-expression at offset {pos}")
            break
        pos = m.end()
        if m[1]:
            stack.append([])
        elif m[2]:
            if len(stack) < 2:
                raise ValueError("unbalanced ')'")
            done = stack.pop()
            stack[-1].append(done)
        elif m[3] is not None:
            stack[-1].append(re.sub(r"\\(.)", r"\1", m[3]))
        else:
            stack[-1].append(m[4])
    if len(stack) != 1:
        raise ValueError("unbalanced '('")
    return stack[0]


@dataclass(frozen=True)
class Placed:
    """A fixture footprint as found on the board, KiCad coordinates (Y down)."""

    reference: str
    footprint: str
    x: float
    y: float
    rotation: float
    layer: str
    properties: dict[str, str]


def find(board: Path) -> list[Placed]:
    tree = parse_sexpr(board.read_text(encoding="utf-8"))
    pcb = tree[0] if tree and isinstance(tree[0], list) else []
    found = []
    for item in pcb:
        if not (isinstance(item, list) and item and item[0] == "footprint"):
            continue
        fields = {c[0]: c for c in item if isinstance(c, list) and c}
        props = {c[1]: c[2] for c in item
                 if isinstance(c, list) and len(c) >= 3 and c[0] == "property"}
        if PROP_FIXTURE not in props:
            continue
        at = fields.get("at", ["at", "0", "0"])
        found.append(Placed(
            reference=props.get("Reference", "?"),
            footprint=item[1],
            x=float(at[1]), y=float(at[2]),
            rotation=float(at[3]) if len(at) > 3 else 0.0,
            layer=fields.get("layer", ["layer", "F.Cu"])[1],
            properties=props,
        ))
    return found


def work_offset(placed: Placed) -> tuple[float, float]:
    """pcb2gcode x/y-offset that puts the footprint origin at work zero.

    KiCad exports Gerbers in absolute board coordinates with Y negated, so the
    stock corner (x, y) on the board is at (x, -y) in the Gerbers.
    """
    return -placed.x, placed.y


def check(
    fixture: Fixture,
    placed: Placed,
    stock_size: tuple[float, float],
    board_box: tuple[float, float, float, float],
    outline_cutter_mm: float | None,
) -> list[str]:
    """``board_box`` is the outline bounding box in the stock frame."""
    p = placed.properties
    key = p.get(PROP_STOCK, "")
    where = f"fixture footprint {placed.reference}"
    if p.get(PROP_FIXTURE) != fixture.name:
        return [f"{where} is for fixture '{p.get(PROP_FIXTURE)}', the recipe uses '{fixture.name}'"]
    if key not in fixture.stocks:
        return [f"{where}: stock '{key}' is not in fixture '{fixture.name}' "
                f"(known: {', '.join(fixture.stocks)})"]
    problems = []
    if p.get(PROP_GEOMETRY) != geometry(fixture, key):
        problems.append(f"{where} is out of date with the fixture file: run 'pcbcam fixture-footprint', "
                        "then Tools > Update Footprints from Library in KiCad")
    if placed.layer != "F.Cu" or abs(placed.rotation) > 1e-6:
        problems.append(f"{where} must not be rotated or flipped (it is at {placed.rotation} deg on {placed.layer})")
    s = fixture.stocks[key]
    if (s.size_x_mm, s.size_y_mm) != stock_size:
        problems.append(f"{where} is a {_fmt(s.size_x_mm)} x {_fmt(s.size_y_mm)} mm stock, the recipe says "
                        f"{_fmt(stock_size[0])} x {_fmt(stock_size[1])} mm")
    if problems:
        return problems

    x0, y0, x1, y1 = board_box
    e = fixture.edge_margin_mm
    if x0 < e or y0 < e or x1 > s.size_x_mm - e or y1 > s.size_y_mm - e:
        problems.append(
            f"board outline ({_fmt(x0)}, {_fmt(y0)}) - ({_fmt(x1)}, {_fmt(y1)}) mm is not inside the stock "
            f"minus its {_fmt(e)} mm edge margin (0, 0) - ({_fmt(s.size_x_mm)}, {_fmt(s.size_y_mm)})")
    keep = fixture.pin_diameter_mm / 2 + fixture.pin_clearance_mm
    for px, py in s.pins_mm:
        dx = max(x0 - px, 0.0, px - x1)
        dy = max(y0 - py, 0.0, py - y1)
        if math.hypot(dx, dy) < keep - 1e-9:
            problems.append(f"board outline comes within {math.hypot(dx, dy):.2f} mm of the pin at "
                            f"({_fmt(px)}, {_fmt(py)}); keep {_fmt(keep)} mm (pin radius + clearance)")
    if outline_cutter_mm is not None and fixture.pin_clearance_mm < outline_cutter_mm:
        problems.append(f"fixture pin_clearance_mm ({_fmt(fixture.pin_clearance_mm)}) is less than the outline "
                        f"cutter ({_fmt(outline_cutter_mm)} mm): the outline could cut into a pin")
    return problems
