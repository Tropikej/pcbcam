"""Render a pcb2gcode ``millproject`` from a resolved recipe.

Only options checked against pcb2gcode 3.0.4's ``src/options.cpp`` are emitted.
Lengths are written in mm with ``metric=true``; times carry explicit units.
Per-tool spindle speeds are applied later by the post-processor, because
pcb2gcode only takes one speed per operation.
"""

from __future__ import annotations

from .config import Recipe
from .tooling import HoleAssignment, Resolved


def _fmt(v: float) -> str:
    return f"{v:.4f}".rstrip("0").rstrip(".")


def render(
    recipe: Recipe,
    resolved: Resolved,
    holes: list[HoleAssignment],
    files: dict[str, str],
) -> str:
    """``files`` maps pcb2gcode inputs (front, outline, drill) to container paths."""
    h = recipe.heights
    lines: dict[str, str] = {
        "metric": "true",
        "metricoutput": "true",
        "zero-start": "true",
        "x-offset": _fmt(-recipe.placement.margin_x_mm),
        "y-offset": _fmt(-recipe.placement.margin_y_mm),
        "zsafe": _fmt(h.safe_mm),
        "zchange": _fmt(h.tool_change_mm),
        "nog64": "true",
        "nog81": "true",
        "nog91-1": "true",
        "spinup-time": "3000ms",
        "spindown-time": "2000ms",
        "optimise": "0.005mm",
        "basename": "board",
    }

    iso = recipe.isolation
    lines.update({
        "front": files["front"],
        "mill-diameters": ",".join(f"{_fmt(t.width_mm)}mm" for t in resolved.isolation),
        "milling-overlap": f"{_fmt(iso.overlap_percent)}%",
        "zwork": _fmt(-iso.depth_mm),
        "mill-feed": _fmt(min(t.tool.feed_mm_min for t in resolved.isolation)),
        "mill-vertfeed": _fmt(min(t.tool.plunge_mm_min for t in resolved.isolation)),
        "mill-speed": _fmt(resolved.isolation[0].tool.rpm),
    })
    if iso.isolation_width_mm:
        lines["isolation-width"] = f"{_fmt(iso.isolation_width_mm)}mm"

    drilled = [a for a in holes if a.method == "drill"]
    milled = [a for a in holes if a.method == "milldrill"]
    if recipe.drilling and recipe.drilling.enabled and (drilled or milled) and "drill" in files:
        d = recipe.drilling
        lines.update({
            "drill": files["drill"],
            "zdrill": _fmt(-d.depth_mm),
            "drill-feed": _fmt(min(t.tool.plunge_mm_min for t in resolved.drills)),
            "drill-speed": _fmt(resolved.drills[0].tool.rpm),
            "drill-side": "front",
            # Round each KiCad size onto the bit that will make it.
            "drills-available": ",".join(
                f"{_fmt(t.width_mm)}mm:{_fmt(d.match_tolerance_mm)}mm" for t in resolved.drills
            ),
        })
        if milled and resolved.milldrill:
            smallest_milled = min(a.diameter_mm for a in milled)
            lines.update({
                "milldrill-diameter": f"{_fmt(resolved.milldrill.width_mm)}mm",
                "min-milldrill-hole-diameter": f"{_fmt(smallest_milled - 1e-3)}mm",
                "zmilldrill": _fmt(-d.depth_mm),
            })

    o = recipe.outline
    if o and o.enabled and resolved.outline:
        t = resolved.outline.tool
        lines.update({
            "outline": files["outline"],
            "cutter-diameter": _fmt(resolved.outline.width_mm),
            "zcut": _fmt(-o.depth_mm),
            "cut-infeed": _fmt(o.stepdown_mm),
            "cut-feed": _fmt(t.feed_mm_min),
            "cut-vertfeed": _fmt(t.plunge_mm_min),
            "cut-speed": _fmt(t.rpm),
            "cut-side": "front",
            "fill-outline": "true",
        })
        if o.tabs.count:
            lines.update({
                "bridges": _fmt(o.tabs.width_mm),
                "bridgesnum": str(o.tabs.count),
                "zbridges": _fmt(-(recipe.stock.thickness_mm - o.tabs.height_mm)),
            })

    body = "\n".join(f"{k}={v}" for k, v in lines.items())
    return "# Generated by pcbcam -- do not edit, change the recipe instead.\n" + body + "\n"
